-- Append-only ledger of seed stock changes. A movement outlives its batch:
-- deleting the batch only clears the reference.
CREATE TABLE seed_stock_movement (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    org_id            BIGINT NOT NULL REFERENCES organization(id) ON DELETE CASCADE,
    seed_inventory_id BIGINT REFERENCES seed_inventory(id) ON DELETE SET NULL,
    species_id        BIGINT NOT NULL REFERENCES species(id) ON DELETE CASCADE,
    kind              VARCHAR(20) NOT NULL CHECK (kind IN ('OPENING', 'ADDED', 'SOWN', 'ADJUSTED')),
    quantity          INT NOT NULL,
    shortfall         INT NOT NULL DEFAULT 0 CHECK (shortfall >= 0),
    unit_cost_cents   INT,
    occurred_on       DATE NOT NULL,
    season_id         BIGINT REFERENCES season(id) ON DELETE SET NULL,
    first_plant_id    BIGINT REFERENCES plant(id) ON DELETE SET NULL,
    plant_count       INT,
    created_at        TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE INDEX idx_seed_stock_movement_org_species ON seed_stock_movement (org_id, species_id);
CREATE INDEX idx_seed_stock_movement_inventory ON seed_stock_movement (seed_inventory_id);
CREATE INDEX idx_seed_stock_movement_season ON seed_stock_movement (season_id);

ALTER TABLE plant ADD COLUMN origin VARCHAR(20) NOT NULL DEFAULT 'SOWN' CHECK (origin IN ('SOWN', 'REGISTERED'));

CREATE TABLE seed_order_line (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    org_id     BIGINT NOT NULL REFERENCES organization(id) ON DELETE CASCADE,
    season_id  BIGINT NOT NULL REFERENCES season(id) ON DELETE CASCADE,
    species_id BIGINT NOT NULL REFERENCES species(id) ON DELETE CASCADE,
    quantity   INT NOT NULL CHECK (quantity >= 0),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    UNIQUE (org_id, season_id, species_id)
);

-- Existing stock enters the ledger as its opening balance.
INSERT INTO seed_stock_movement (org_id, seed_inventory_id, species_id, kind, quantity, unit_cost_cents, occurred_on, season_id)
SELECT org_id, id, species_id, 'OPENING', quantity, cost_per_unit_cents, CURRENT_DATE, NULL
FROM seed_inventory
WHERE quantity > 0;
